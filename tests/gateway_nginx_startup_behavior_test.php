spl_autoload_register(static function (string $class): void {
    if (str_starts_with($class, 'Scf\\')) {
        $path = dirname(__DIR__) . '/src/' . str_replace('\\', '/', substr($class, 4)) . '.php';
        if (is_file($path)) require_once $path;
    }
